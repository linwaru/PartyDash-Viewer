@dataclass
class Translator:
    locale: str = "pt-BR"
    changed: Callable[[str], None] | None = None

    def text(self, key: str, **values: object) -> str:
        catalog = T.get(self.locale, T["en-US"])
        value = catalog.get(key, T["en-US"].get(key, key))
        try:
            return value.format(**values)
        except (KeyError, IndexError):
            return value

    def set_locale(self, locale: str) -> None:
        if locale not in LANGUAGES:
            return
        self.locale = locale
        if self.changed:
            self.changed(locale)
